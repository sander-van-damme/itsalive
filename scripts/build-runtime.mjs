import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
const result = await build({
  entryPoints: ["src/runtime/index.tsx"],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "__ITSALIVE_RUNTIME__",
  platform: "browser",
  target: "es2022",
  minify: true,
  define: { "process.env.NODE_ENV": '"development"' },
});
const source = result.outputFiles[0].text;
await writeFile(
  "src/shell/runtime-source.generated.ts",
  `// Generated by scripts/build-runtime.mjs. Do not edit.\nexport const runtimeSource = ${JSON.stringify(source)};\n`,
);
console.log(`Shell-owned runtime: ${Math.round(source.length / 1024)} KiB`);
